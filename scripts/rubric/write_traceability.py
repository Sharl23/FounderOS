"""Regenerate docs/rubric-traceability.md from policy/rubric_phase1.yaml (run from repo root)."""
import sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / 'backend'))
from app import rubric  # noqa: E402

SPECIFIC = {
    'must_have_pain': 'test_same_organisation_twice_is_one_source_and_strong_is_capped; test_founder_supplied_paste_is_labelled_and_cannot_reach_strong_alone; test_wrong_source_type_metadata_and_example_com_never_count; ui_e2e step 5',
    'no_blocking_patent': 'test_absence_checks_never_strong_and_weak_needs_negative_evidence; test_research_queries_use_structured_fields_not_truncated_text; ui_e2e step 5',
    'current_alternatives_in_use': 'test_absence_checks_never_strong_and_weak_needs_negative_evidence; test_judge_output_with_fake_ids_or_numbers_falls_back_to_unknown',
    'price_gaps': 'test_wrong_source_type_metadata_and_example_com_never_count (academic passage refused)',
    'raw_counts_discounted': 'test_no_evidence_means_every_scored_check_unknown_and_no_fabrication (NOT_APPLICABLE only when no figures exist)',
    'current_workaround_pain': 'test_granular_ratings_aggregate_into_dimension_in_code', 'customer_own_words': 'test_granular_ratings_aggregate_into_dimension_in_code',
    'free_alternatives_threat': 'test_no_evidence_means_every_scored_check_unknown_and_no_fabrication', 'direct_competitors_mapped': 'test_no_evidence_means_every_scored_check_unknown_and_no_fabrication',
    'regulatory_barriers_manageable': 'test_no_evidence_means_every_scored_check_unknown_and_no_fabrication', 'comparable_firms_revenue': 'test_no_evidence_means_every_scored_check_unknown_and_no_fabrication',
    'illegal_in_target_market': 'test_children_brief_flags_minors_and_unknown_jurisdiction_research_only; test_safety_rules_v7.py::test_official_source_can_hard_stop_only_when_verified_and_official',
    'regulated_or_sensitive_area': 'test_children_brief_flags_minors_and_unknown_jurisdiction_research_only; test_safety_rules_v7.py',
}
rows = []
for c in rubric.CHECKS:
    o = rubric.OV[c['id']]
    p = rubric.PROVENANCE[c['id']]
    engine = ('safety.py + policy/safety_rules.yaml (enforced); rubric.py registers it under D01' if c['kind'] == 'knockout'
              else 'rubric.evaluate_check -> per-check judge (rubric.validate_judgment) -> rubric.aggregate -> criteria._with_granular')
    extras = []
    if o.get('absence_claim_cap'):
        extras.append('never STRONG (absence)')
    if o.get('brief_condition'):
        extras.append(f'brief condition {o["brief_condition"]} can give WEAK')
    types = ', '.join(t for t in o['accepted_source_types'])
    tests = 'test_v08_contract.py (all-67 schema, count, hash, mapping)' + ('; ' + SPECIFIC[c['id']] if c['id'] in SPECIFIC else '')
    rows.append(f"| `{c['id']}` | {rubric.DIMENSION_OF[c['id']]} | {c['kind']} | {o['sources_required']} | {types} | {'; '.join(extras) or '—'} | {engine} | {tests} | {p['book'][:70]}; {p['chapter'][:70]}; page {p['page']} |")
hdr = f"""# Team rubric traceability: all 67 Phase-1 checks

Generated by `scripts/rubric/write_traceability.py` from `backend/policy/rubric_phase1.yaml` ({rubric.VERSION}, team data sha256 `{rubric.DOC['team_data_sha256'][:16]}…`).

How to read it:
* **Dimension**: the original criterion the check aggregates into (D01 safety; D03–D07 scored). D02, D08, D09 and X01–X05 stay separate top-level criteria.
* **Sources required / accepted types**: FounderOS's implementation overlay, derived from each `research_instruction` (labelled TEAM_ASSUMPTION in the YAML). Academic metadata, simulated results and book passages are never eligible.
* **Provenance**: team-supplied reference. Page is "not visible" everywhere; FounderOS has **not** checked the quotations against the books. A supporting passage is the rationale for a check, never evidence that a venture meets it.
* Statuses: UNKNOWN (no eligible evidence, or judge output rejected), AWAITING_JUDGE, WEAK/MIXED/STRONG (validated judgment capped by code; mapped to 2/3/4), NOT_APPLICABLE (code rule only). WEAK needs a cited challenging source or a directly checkable brief condition.

| Check id | Dim | Kind | Sources req. | Accepted source types | Code limits | Engine | Tests | Provenance (team-supplied) |
|---|---|---|---|---|---|---|---|---|
"""
(ROOT / 'docs' / 'rubric-traceability.md').write_text(hdr + '\n'.join(rows) + '\n', encoding='utf-8')
print(len(rows), 'rows')
